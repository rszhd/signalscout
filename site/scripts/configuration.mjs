/**
 * Writes `self-hosting/configuration.md` from the repository's `.env.example`.
 * US-344.
 *
 * `.env.example` names every setting the application reads, with the reason
 * beside it, and `env-example.test.ts` fails when one is missing. A second
 * table written by hand would be the drift BUG-339 spent a morning finding, so
 * the page is generated and the example file stays the one source.
 *
 * The file's shape is what this reads: a `# ---- name` line opens a section,
 * and a block of comment lines followed by `NAME=value` lines, ended by a
 * blank line, is one entry. Runs before `npm run dev` and `npm run build`.
 * The output is committed, so an agent reading the repository finds it too.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const example = readFileSync(join(root, ".env.example"), "utf8");
const selfHosted = readFileSync(join(root, ".env.example.self-hosted"), "utf8");
const output = join(here, "..", "self-hosting", "configuration.md");

const variable = /^([A-Z][A-Z0-9_]+)=(.*)$/;
const section = /^# -{5,} (.+)$/;
const inShortFile = new Set(
  selfHosted
    .split("\n")
    .map((line) => line.match(variable)?.[1])
    .filter(Boolean),
);

/** Strips the quotes and any trailing comment from a value. */
function defaultOf(raw) {
  const value = raw.replace(/\s+#.*$/, "").trim();
  return value === "''" || value === '""' ? "" : value;
}

/**
 * Turns a comment block into Markdown.
 *
 * Two shapes need more than stripping the `#`. An option line —
 * `closed — the default…`, its continuation indented under the text — becomes
 * a list item, or Markdown runs the options together into one paragraph. A
 * line indented four spaces outside an option is a command, and becomes code.
 */
function prose(lines) {
  const out = [];
  let code = false;
  let option = false;
  const closeCode = () => {
    while (out.length > 0 && out.at(-1) === "") out.pop();
    out.push("```", "");
    code = false;
  };
  for (const line of lines) {
    const text = line.replace(/^# ?/, "");
    const opening = text.match(/^([\w.|-]+)\s+— (.*)$/);
    if (opening) {
      if (code) closeCode();
      if (!option) out.push("");
      out.push(`- \`${opening[1]}\` — ${opening[2]}`);
      option = true;
      continue;
    }
    if (option && /^ {2,}\S/.test(text)) {
      out[out.length - 1] += ` ${text.trim()}`;
      continue;
    }
    option = false;
    const isCode = /^ {4}\S/.test(text);
    if (isCode && !code) {
      out.push("", "```");
      code = true;
    }
    if (!isCode && code && text.trim() !== "") closeCode();
    out.push(isCode ? text.slice(4) : text);
  }
  if (code) closeCode();
  return out
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const sections = [];
let current = null;
let block = [];

function closeBlock() {
  const names = block.filter((l) => variable.test(l)).map((l) => l.match(variable));
  if (names.length > 0 && current) {
    current.entries.push({
      names: names.map((m) => m[1]),
      defaults: names.map((m) => defaultOf(m[2])),
      text: prose(block.filter((l) => l.startsWith("#"))),
    });
  }
  block = [];
}

for (const line of example.split("\n")) {
  const heading = line.match(section);
  if (heading) {
    closeBlock();
    current = { name: heading[1].trim(), entries: [] };
    sections.push(current);
  } else if (line.trim() === "") {
    closeBlock();
  } else {
    block.push(line);
  }
}
closeBlock();

const title = (name) => name.charAt(0).toUpperCase() + name.slice(1);
const page = [
  "<!-- Generated by site/scripts/configuration.mjs from .env.example. Edit that file, not this one. -->",
  "",
  "# Configuration reference",
  "",
  "Every setting SignalScout reads, in the order `.env.example` lists them, with",
  "the reason written beside each one. Set a value in the `.env` file next to",
  "`docker-compose.yml`, then run `docker compose up -d` so the containers read it.",
  "",
  "You rarely need more than the short file you copied at install,",
  "`.env.example.self-hosted`. A setting marked **in the short file** is one it",
  "already names. Every other setting has a default that is the self-hosted",
  "answer.",
  "",
];

for (const s of sections) {
  if (s.entries.length === 0) continue;
  page.push(`## ${title(s.name)}`, "");
  for (const entry of s.entries) {
    page.push(`### ${entry.names.map((n) => `\`${n}\``).join(", ")}`, "");
    const fact = (n, i) => {
      const value = entry.defaults[i];
      const shown = value === "" ? "*empty*" : `\`${value}\``;
      const short = inShortFile.has(n) ? " · **in the short file**" : "";
      return `${shown}${short}`;
    };
    if (entry.names.length === 1) {
      page.push(`Default: ${fact(entry.names[0], 0)}`, "");
    } else {
      page.push(...entry.names.map((n, i) => `- \`${n}\` — default ${fact(n, i)}`), "");
    }
    if (entry.text) page.push(entry.text, "");
  }
}

writeFileSync(output, `${page.join("\n").trim()}\n`);
console.log(`configuration.md: ${sections.reduce((n, s) => n + s.entries.length, 0)} entries`);
